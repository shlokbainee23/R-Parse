"""Builds the R-PARSE browser favicon set from the approved R/P monogram master.

Usage:
    python scripts/build_favicons.py [path/to/master.png]

The master defaults to brand/rparse-monogram.png. When a different path is given
it is copied into brand/ first so the repository always holds the source asset.

Outputs (all derived by resampling only; geometry and colours are untouched):
    brand/favicon.ico            16, 32, 48 px (PNG-compressed ICO entries)
    brand/favicon-32x32.png      32 px, transparent
    brand/rparse-mark-96.png     96 px, transparent, no padding (header logo on landing + Studio)
    brand/apple-touch-icon.png   180 px, opaque paper background (iOS renders alpha as black)
    favicon.svg                  SVG container embedding the 128 px raster, for the legacy /favicon.svg route
"""

import base64
import io
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "brand"
MASTER = BRAND / "rparse-monogram.png"

# Alpha below this is anti-aliasing noise around the artwork, not part of the mark.
ALPHA_TRIM_THRESHOLD = 8
TAB_PADDING = 0.04
TOUCH_PADDING = 0.14
PAPER = (247, 245, 240, 255)  # --bg-paper


def load_trimmed_mark(path: Path) -> Image.Image:
    im = Image.open(path).convert("RGBA")
    mask = im.getchannel("A").point(lambda v: 255 if v > ALPHA_TRIM_THRESHOLD else 0)
    bbox = mask.getbbox()
    if bbox is None:
        raise SystemExit(f"{path} has no visible pixels")
    return im.crop(bbox)


def square_canvas(mark: Image.Image, size: int, padding: float, background=(0, 0, 0, 0)) -> Image.Image:
    inner = round(size * (1 - 2 * padding))
    scale = inner / max(mark.width, mark.height)
    w, h = max(1, round(mark.width * scale)), max(1, round(mark.height * scale))
    resized = mark.resize((w, h), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (size, size), background)
    canvas.alpha_composite(resized, ((size - w) // 2, (size - h) // 2))
    return canvas


def main() -> None:
    BRAND.mkdir(exist_ok=True)
    if len(sys.argv) > 1:
        src = Path(sys.argv[1])
        if src.resolve() != MASTER.resolve():
            shutil.copyfile(src, MASTER)

    mark = load_trimmed_mark(MASTER)

    ico_master = square_canvas(mark, 256, TAB_PADDING)
    ico_master.save(BRAND / "favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)])

    square_canvas(mark, 32, TAB_PADDING).save(BRAND / "favicon-32x32.png", optimize=True)
    square_canvas(mark, 96, 0).save(BRAND / "rparse-mark-96.png", optimize=True)
    square_canvas(mark, 180, TOUCH_PADDING, PAPER).convert("RGB").save(
        BRAND / "apple-touch-icon.png", optimize=True
    )

    buf = io.BytesIO()
    square_canvas(mark, 128, TAB_PADDING).save(buf, format="PNG", optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    (ROOT / "favicon.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" width="32" height="32">\n'
        "  <!-- R-PARSE R/P monogram (raster master embedded; generated by scripts/build_favicons.py) -->\n"
        f'  <image width="128" height="128" href="data:image/png;base64,{b64}"/>\n'
        "</svg>\n",
        encoding="utf-8",
        newline="\n",
    )

    for name in ("favicon.ico", "favicon-32x32.png", "rparse-mark-96.png", "apple-touch-icon.png"):
        print(f"wrote brand/{name} ({(BRAND / name).stat().st_size} bytes)")
    print(f"wrote favicon.svg ({(ROOT / 'favicon.svg').stat().st_size} bytes)")


if __name__ == "__main__":
    main()
